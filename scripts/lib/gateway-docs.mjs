// Builds the gateway reference of the developer portal (DEV-PORT-004) from docs/05-api-and-gateway.md, so the
// portal and the specification cannot drift apart: the opcode table of section 6.1 and the dispatch event names
// of section 6.3. `node scripts/lib/gateway-docs.mjs` rewrites apps/web/src/developers/gatewayDocs.generated.ts;
// a test fails when the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const DOC = join(root, 'docs', '05-api-and-gateway.md');
export const OUT = join(root, 'apps', 'web', 'src', 'developers', 'gatewayDocs.generated.ts');

const section = (md, from, to) => {
  const a = md.indexOf(from);
  const b = md.indexOf(to, a + from.length);
  if (a < 0 || b < 0) throw new Error(`section ${from} not found`);
  return md.slice(a + from.length, b);
};

/** Strip markdown emphasis down to plain text. */
const plain = (s) => s.replace(/`/g, '').replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();

/** The opcode rows of section 6.1: `{ op, name, dir, note }`. */
export function opcodes(md) {
  const body = section(md, '### 6.1 Opcodes (Discord numbering)', '### 6.2 Intents');
  const rows = [];
  for (const line of body.split('\n')) {
    if (!line.startsWith('|') || /^\|\s*-/.test(line) || /^\|\s*Op\s*\|/.test(line)) continue;
    // Cells never contain a literal pipe in this table.
    const cells = line
      .slice(1, line.lastIndexOf('|'))
      .split('|')
      .map((c) => c.trim());
    if (cells.length < 3) continue;
    const [op, nameCell, dir] = cells;
    const cell = plain(nameCell);
    const cut = cell.search(/[(:]/);
    rows.push({
      op: plain(op),
      name: (cut < 0 ? cell : cell.slice(0, cut)).trim(),
      dir: plain(dir),
      note:
        cut < 0
          ? ''
          : cell
              .slice(cut)
              .replace(/^[(:]\s*/, '')
              .replace(/\)$/, ''),
    });
  }
  return rows;
}

/** Dispatch event names in the first two paragraphs of section 6.3 (Discord's and the SIDE ROOM additions). */
export function events(md) {
  const body = section(md, '### 6.3 Dispatch events', '### 6.4 Session lifecycle');
  const paras = body.split(/\n\s*\n/).filter((p) => p.trim());
  const text = paras.slice(0, 2).join('\n');
  const found = new Set();
  for (const m of text.matchAll(/`([A-Z][A-Z0-9]*(?:_[A-Z0-9*]+)*)`/g)) found.add(m[1]);
  return [...found];
}

export function render(md) {
  const ops = opcodes(md);
  const evs = events(md);
  return `// Generated by scripts/lib/gateway-docs.mjs from docs/05-api-and-gateway.md sections 6.1 and 6.3. Do not edit.
export interface GatewayOpcode {
  op: string;
  name: string;
  dir: string;
  note: string;
}

export const GATEWAY_OPCODES: GatewayOpcode[] = ${JSON.stringify(ops, null, 2)};

export const GATEWAY_EVENTS: string[] = ${JSON.stringify(evs, null, 2)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render(readFileSync(DOC, 'utf8')));
  console.log(`wrote ${OUT}`);
}
