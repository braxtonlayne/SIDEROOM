//! TypeScript emitter for the UI kit (DS-TOK-001, Q64). The registry is the only source:
//! the output is `packages/ui/src/theme/tokens.generated.ts`, checked for drift by
//! `tests/ts_generated.rs`.

use crate::registry::TOKENS;
use crate::validate::BUILTIN_THEME_IDS;
use std::fmt::Write as _;

/// Path of the committed TypeScript output, relative to the repository root.
pub const TS_OUTPUT_PATH: &str = "packages/ui/src/theme/tokens.generated.ts";

/// Semantic UI tokens: the `--ui-` prefix (the UI kit's `UI_TOKEN_NAMES`).
fn is_ui_token(name: &str) -> bool {
    name.starts_with("--ui-")
}

/// Render the generated TypeScript module: token-name union, UI token list and theme ids.
pub fn typescript() -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p sr-theme --features emit --bin sr-theme-emit -- ts`. Do not edit.\n");
    out.push_str(
        "// Source: crates/sr-theme/src/registry.rs and validate.rs (BUILTIN_THEME_IDS).\n\n",
    );

    out.push_str("/** Every token name in the sr-theme registry, in output order. */\n");
    out.push_str("export const KNOWN_TOKEN_NAMES = [\n");
    for t in TOKENS {
        let _ = writeln!(out, "  \"{}\",", t.name);
    }
    out.push_str("] as const;\n");
    out.push_str("export type KnownTokenName = (typeof KNOWN_TOKEN_NAMES)[number];\n\n");

    out.push_str(
        "/** Semantic tokens every built-in theme defines. Primitives use only these. */\n",
    );
    out.push_str("export const UI_TOKEN_NAMES = [\n");
    for t in TOKENS.iter().filter(|t| is_ui_token(t.name)) {
        let _ = writeln!(out, "  \"{}\",", t.name);
    }
    out.push_str("] as const;\n");
    out.push_str("export type UiTokenName = (typeof UI_TOKEN_NAMES)[number];\n\n");

    out.push_str("/** Built-in theme ids (reserved for platform themes). */\n");
    out.push_str("export const THEME_IDS = [\n");
    for id in BUILTIN_THEME_IDS {
        let _ = writeln!(out, "  \"{id}\",");
    }
    out.push_str("] as const;\n");
    out.push_str("export type ThemeId = (typeof THEME_IDS)[number];\n");
    out
}
