#[cfg(test)]
pub(crate) fn table() -> &'static [(&'static str, &'static str)] {
    SHORTCODES
}

/// Look up a shortcode name (without colons), case-insensitively.
pub fn shortcode_to_emoji(name: &str) -> Option<&'static str> {
    if name.is_empty() || name.len() > 40 {
        return None;
    }
    SHORTCODES
        .iter()
        .find(|(n, _)| n.eq_ignore_ascii_case(name))
        .map(|&(_, e)| e)
}

/// Number of shortcodes in the table (aliases included).
pub fn shortcode_count() -> usize {
    SHORTCODES.len()
}

/// Valid shortcode name character.
pub(crate) fn is_shortcode_char(c: u8) -> bool {
    c.is_ascii_alphanumeric() || matches!(c, b'_' | b'+' | b'-')
}

fn is_emoji_base(c: char) -> bool {
    matches!(c as u32,
        0x1F300..=0x1FAFF | 0x1F000..=0x1F2FF | 0x2600..=0x27BF | 0x2B00..=0x2BFF
        | 0x2190..=0x21FF | 0x2300..=0x23FF | 0x25A0..=0x25FF | 0x2900..=0x297F
        | 0x00A9 | 0x00AE | 0x203C | 0x2049 | 0x2122 | 0x2139 | 0x24C2
        | 0x3030 | 0x303D | 0x3297 | 0x3299)
}

fn is_regional(c: char) -> bool {
    matches!(c as u32, 0x1F1E6..=0x1F1FF)
}

fn is_modifier(c: char) -> bool {
    matches!(c as u32, 0xFE0F | 0x20E3 | 0x1F3FB..=0x1F3FF | 0xE0020..=0xE007F)
}

/// Count emoji grapheme clusters in `s`. Returns `None` if `s` contains anything other
/// than emoji and whitespace. Whitespace-only input counts as zero.
pub fn count_emoji_only(s: &str) -> Option<usize> {
    let cs: Vec<char> = s.chars().collect();
    let mut i = 0;
    let mut n = 0;
    while i < cs.len() {
        let c = cs[i];
        if c.is_whitespace() {
            i += 1;
            continue;
        }
        if is_regional(c) {
            i += if cs.get(i + 1).copied().is_some_and(is_regional) {
                2
            } else {
                1
            };
            n += 1;
            continue;
        }
        let keycap = (c.is_ascii_digit() || c == '#' || c == '*')
            && (cs.get(i + 1) == Some(&'\u{20E3}')
                || (cs.get(i + 1) == Some(&'\u{FE0F}') && cs.get(i + 2) == Some(&'\u{20E3}')));
        if !(keycap || is_emoji_base(c)) {
            return None;
        }
        i += 1;
        loop {
            match cs.get(i) {
                Some(&m) if is_modifier(m) => i += 1,
                Some('\u{200D}')
                    if cs
                        .get(i + 1)
                        .is_some_and(|&x| is_emoji_base(x) || is_regional(x)) =>
                {
                    i += 2
                }
                _ => break,
            }
        }
        n += 1;
    }
    Some(n)
}

/// Replace `:shortcode:` names with their unicode emoji (Q89). The composer calls this at
/// send time; the renderer parser leaves `:name:` literal. Unknown names stay as written.
pub fn expand_shortcodes(input: &str) -> String {
    let b = input.as_bytes();
    let mut out = String::with_capacity(input.len());
    let mut i = 0;
    while i < b.len() {
        // Custom emoji syntax (`<:name:id>`, `<a:name:id>`) is left alone.
        let custom = (i >= 1 && b[i - 1] == b'<') || (i >= 2 && &b[i - 2..i] == b"<a");
        if b[i] == b':'
            && !custom
            && let Some(n) = b[i + 1..]
                .iter()
                .take(41)
                .position(|&c| !is_shortcode_char(c))
            && n > 0
            && b.get(i + 1 + n) == Some(&b':')
            && let Some(emoji) = shortcode_to_emoji(&input[i + 1..i + 1 + n])
        {
            out.push_str(emoji);
            i += n + 2;
            continue;
        }
        let ch = input[i..].chars().next().unwrap_or('\u{fffd}');
        out.push(ch);
        i += ch.len_utf8().max(1);
    }
    out
}

/// If the message consists solely of emoji (unicode, custom) and whitespace, return the
/// emoji count (no cap). Otherwise `None`.
pub fn emoji_only_count(nodes: &[Node]) -> Option<usize> {
    let mut total = 0;
    for n in nodes {
        match n {
            Node::Text { text } => total += count_emoji_only(text)?,
            Node::CustomEmoji { .. } => total += 1,
            Node::LineBreak => {}
            _ => return None,
        }
    }
    Some(total)
}

/// True when the message should render with jumbo emoji: 1 to [`JUMBO_MAX`] emoji and
/// nothing else.
pub fn is_jumbo(nodes: &[Node]) -> bool {
    matches!(emoji_only_count(nodes), Some(n) if (1..=JUMBO_MAX).contains(&n))
}
