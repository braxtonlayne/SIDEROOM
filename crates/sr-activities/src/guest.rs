//! Guest links (ARC-GST-001, roadmap P28 wave 43, D-385, D-397, D-399): the shared contract.
//!
//! This module is the agreement between the relay (routes, the gateway guest socket, the `sr-voice` lobby
//! sub-room) and the client runner (ARC-GST-002). Everything a guest may touch is named here.
//!
//! ```text
//! POST   /api/v1/activity-instances/{instance_id}/guest-links                 member of the running instance
//!        -> 201 GuestLinkCreated { lobby_token, expires_at }
//! DELETE /api/v1/activity-instances/{instance_id}/guest-links/{lobby_token}   lobby host / instance host
//!        -> 204
//! POST   /api/v1/play/{lobby_token}/join                                      unauthenticated, rate limited
//!        -> 200 GuestJoined { guest_token, callsign, expires_at, topic, socket_path, application_id, ... }
//! GET    /gateway/guest?v=1   (WebSocket; the frames are in sr_gateway::guest)
//! ```
//!
//! * The `#key=` fragment of the shared link (`/play/<lobby_token>#key=<ephemeral_game_key>`) is generated by the
//!   client and never sent to the server. Frames on the lobby are opaque to the relay.
//! * A lobby token is 64 lowercase hex digits (two UUIDv4s from Postgres' random source), shown once; the server
//!   keeps only its SHA-256. A guest token is `srg_` plus 64 hex digits, also digest-only.
//! * A guest token is accepted by the guest socket and by nothing else: every REST route answers it with 403.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use utoipa::ToSchema;

/// The one topic a guest socket may hold: `game:<lobby_token>`.
pub const TOPIC_PREFIX: &str = "game:";
/// Length of a lobby token (hex digits).
pub const LOBBY_TOKEN_LEN: usize = 64;
/// A guest token starts with this, so every credential check can tell it from a session or bot token.
pub const GUEST_TOKEN_PREFIX: &str = "srg_";
/// Length of a guest token: the prefix and 64 hex digits.
pub const GUEST_TOKEN_LEN: usize = GUEST_TOKEN_PREFIX.len() + 64;
/// Where the guest socket is served (the public listener, beside `/gateway`).
pub const SOCKET_PATH: &str = "/gateway/guest";
/// A link lives this long unless the lobby ends or the host revokes it first.
pub const LINK_TTL_SECS: i64 = 6 * 3600;
/// A guest session lives this long, and never past its link.
pub const SESSION_TTL_SECS: i64 = 2 * 3600;
/// Guest sessions one lobby admits at once (the relay also caps seats).
pub const MAX_GUESTS_PER_LOBBY: i64 = 16;
/// Unrevoked, unexpired links one instance may hold.
pub const MAX_LINKS_PER_INSTANCE: i64 = 5;

/// A response to creating a guest link.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[schema(as = ArcadeGuestLinkCreated)]
pub struct GuestLinkCreated {
    /// 64 hex digits, shown once. The page is `/play/<lobby_token>#key=<key>`; the client adds the key.
    pub lobby_token: String,
    /// When the link stops working (RFC 3339, UTC); earlier if the host revokes it or the lobby ends.
    pub expires_at: String,
}

/// A response to a guest joining.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[schema(as = ArcadeGuestJoined)]
pub struct GuestJoined {
    /// `srg_` plus 64 hex digits. Sent as the `hello` of the guest socket; no REST route accepts it.
    pub guest_token: String,
    /// The random callsign the lobby shows for this guest.
    pub callsign: String,
    /// When the guest session ends (RFC 3339, UTC); never later than the link.
    pub expires_at: String,
    /// The one topic the guest socket may hold: `game:<lobby_token>`.
    pub topic: String,
    /// The guest socket's path on the same origin.
    pub socket_path: String,
    /// The game the lobby runs, so the runner loads its bundle (and nothing else of the server).
    pub application_id: String,
    /// The game's name.
    pub application_name: String,
    /// The manifest flags the game declares (sorted), reserved ones included (`ingame_voice`), so the runner can
    /// refuse a capability that has not shipped. Flag names only; nothing else of the manifest.
    pub capabilities: Vec<String>,
    /// OPS-TDEP-001 (D-450), test deployments only: `/_activity/<application_id>/` when the server serves Activities
    /// from a path on its own host (`[activities] origin_mode = "same_host_sandboxed"`). Absent in the default mode,
    /// where the game's frame is `<application_id>.activities.<host>`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub frame_path: Option<String>,
}

/// What the guest socket learns about a guest session or a member seat when it checks a credential.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Seating {
    /// SHA-256 of the lobby token: the relay's only name for the lobby.
    pub lobby: [u8; 32],
    /// `true` for a signed-in member of the instance, `false` for a guest.
    pub member: bool,
    /// What the lobby shows for this seat.
    pub callsign: String,
}

/// The topic of a lobby.
pub fn topic_of(lobby_token: &str) -> String {
    format!("{TOPIC_PREFIX}{lobby_token}")
}

/// The lobby token in a topic, if the topic has the shape `game:<64 hex digits>`.
pub fn lobby_token_of(topic: &str) -> Option<&str> {
    let t = topic.strip_prefix(TOPIC_PREFIX)?;
    is_lobby_token(t).then_some(t)
}

fn is_hex64(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

/// Whether `s` has the shape of a lobby token.
pub fn is_lobby_token(s: &str) -> bool {
    is_hex64(s)
}

/// Whether `s` has the shape of a guest token.
pub fn is_guest_token(s: &str) -> bool {
    s.strip_prefix(GUEST_TOKEN_PREFIX).is_some_and(is_hex64)
}

/// The stored form of a lobby or guest token.
pub fn digest(token: &str) -> Vec<u8> {
    Sha256::digest(token.as_bytes()).to_vec()
}

/// [`digest`] as the fixed-size name the relay uses.
pub fn lobby_id(lobby_token: &str) -> [u8; 32] {
    Sha256::digest(lobby_token.as_bytes()).into()
}

const ADJECTIVES: [&str; 16] = [
    "Amber", "Brisk", "Cobalt", "Dusky", "Ember", "Frosty", "Gentle", "Hazel", "Indigo", "Jolly",
    "Keen", "Lunar", "Mellow", "Nimble", "Olive", "Plucky",
];
const ANIMALS: [&str; 16] = [
    "Badger", "Crane", "Dingo", "Egret", "Ferret", "Gecko", "Heron", "Ibis", "Jackal", "Koala",
    "Lemur", "Marten", "Newt", "Otter", "Panda", "Quail",
];

/// A random callsign such as `Amber Otter 42` from four random bytes. Guests never choose a name (the lobby
/// shows only this), so nothing a guest types reaches the other players.
pub fn callsign(random: [u8; 4]) -> String {
    format!(
        "{} {} {}",
        ADJECTIVES[usize::from(random[0] & 15)],
        ANIMALS[usize::from(random[1] & 15)],
        10 + u16::from(random[2]) % 90
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn topics_round_trip_and_reject_other_shapes() {
        let t = "ab".repeat(32);
        assert_eq!(lobby_token_of(&topic_of(&t)), Some(t.as_str()));
        assert_eq!(lobby_token_of(&format!("game:{}", "AB".repeat(32))), None);
        assert_eq!(lobby_token_of("game:abc"), None);
        assert_eq!(lobby_token_of(&format!("guild:{t}")), None);
        assert_eq!(lobby_token_of(&format!("game:{t}x")), None);
        assert_eq!(lobby_token_of(&t), None);
    }

    #[test]
    fn guest_tokens_have_a_prefix_and_lobby_tokens_do_not() {
        let hex = "0f".repeat(32);
        assert!(is_guest_token(&format!("srg_{hex}")));
        assert!(!is_guest_token(&hex));
        assert!(!is_guest_token("srg_short"));
        assert!(is_lobby_token(&hex));
        assert!(!is_lobby_token(&format!("srg_{hex}")));
    }

    #[test]
    fn callsigns_are_fixed_vocabulary() {
        assert_eq!(callsign([0, 0, 0, 0]), "Amber Badger 10");
        assert_eq!(callsign([255, 255, 255, 255]).split(' ').count(), 3);
    }

    #[test]
    fn digests_are_sha256_and_agree() {
        assert_eq!(digest("a").len(), 32);
        assert_ne!(digest("a"), digest("b"));
        assert_eq!(digest("a"), lobby_id("a").to_vec());
    }
}
