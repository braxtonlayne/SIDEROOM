// @ts-check
// Writes replay/script.js, the recorded input script of the determinism gate: 900 ticks (15 s), two players.
// The first 5 s are choreographed so both players run into the box pyramid from two sides (one jumps into it,
// one crouches through), the rest is seeded "fidgeting" (walk, strafe, turn, jump, crouch) so a lot of contact
// pairs come and go. Re-run only to change the script on purpose:
//   node replay/make-script.mjs
// The output is committed; the gate always replays the committed file.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Rng } from '../sim/rng.js';
import { BTN, wrapYaw, clampPitch } from '../sim/input.js';

const TICKS = 900;
/** @type {[number, number, number, number, number][]} */
const events = [];
/** @param {number} tick @param {number} slot @param {number} buttons @param {number} yaw @param {number} [pitch] */
const at = (tick, slot, buttons, yaw, pitch = 0) => events.push([tick, slot, buttons, wrapYaw(yaw), clampPitch(pitch)]);

// Player 0 spawns at (0, 0, 8) looking down -Z, straight at the pyramid at z = 3.
at(0, 0, 0, 0);
at(20, 0, BTN.FORWARD, 0);
at(70, 0, BTN.FORWARD | BTN.JUMP, 0);
at(72, 0, BTN.FORWARD, 0);
at(150, 0, BTN.FORWARD | BTN.LEFT, 1200);
at(210, 0, BTN.FORWARD, -3000, -2000);
at(260, 0, BTN.BACK | BTN.RIGHT, -3000);
// Player 1 spawns at (-6, 0, 6): turn towards the pyramid (yaw about -63 degrees) and push in, crouched part way.
at(0, 1, 0, -11546);
at(30, 1, BTN.FORWARD, -11546);
at(110, 1, BTN.FORWARD | BTN.CROUCH, -11000);
at(170, 1, BTN.FORWARD, -10000);
at(200, 1, BTN.FORWARD | BTN.JUMP, -9000);
at(203, 1, BTN.FORWARD, -9000);
at(250, 1, BTN.RIGHT, -16384);

// From tick 300 on: seeded fidgeting, a new input every 12..40 ticks per player.
const rng = new Rng(0x5eed);
const MOVES = [BTN.FORWARD, BTN.FORWARD | BTN.LEFT, BTN.FORWARD | BTN.RIGHT, BTN.BACK, BTN.LEFT, BTN.RIGHT, BTN.FORWARD | BTN.JUMP, BTN.FORWARD | BTN.CROUCH, 0];
for (let slot = 0; slot < 2; slot++) {
  let t = 300 + slot * 7;
  let yaw = slot === 0 ? -3000 : -16384;
  while (t < TICKS - 30) {
    yaw += rng.int(12000) - 6000;
    at(t, slot, MOVES[rng.int(MOVES.length)], yaw, rng.int(4000) - 2000);
    t += 12 + rng.int(29);
  }
  // Everyone stops for the last 30 ticks so the boxes settle a little.
  at(TICKS - 30, slot, 0, yaw);
}
events.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const script = { version: 1, seed: 0x0a3d0001, ticks: TICKS, players: 2, events };
const out = join(dirname(fileURLToPath(import.meta.url)), 'script.js');
const body = events.map((e) => `    [${e.join(', ')}],`).join('\n');
writeFileSync(
  out,
  `// @ts-check
// GENERATED by replay/make-script.mjs: the recorded input script of the determinism gate. Do not edit by hand.
// [tick, slot, buttons, yaw, pitch]; inputs are sticky until the slot's next event.

/** @type {import('./run.js').ReplayScript} */
export default {
  version: ${script.version},
  seed: ${script.seed},
  ticks: ${script.ticks},
  players: ${script.players},
  events: [
${body}
  ],
};
`,
);
console.log(`wrote ${out}: ${events.length} events over ${TICKS} ticks`);
