const tables = { en };

export function t(key, args = {}, locale = 'en') {
  const table = tables[locale] ?? en;
  const s = table[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(args[k] ?? ''));
}

export const STRING_KEYS = Object.keys(en);
