import { http, HttpResponse, type HttpHandler } from 'msw';
import { mockOperations, type MockOperation } from './handlers.generated';

export { mockOperations, type MockOperation } from './handlers.generated';

export interface CreateHandlersOptions {
  /** Origin and base path matched before each operation path. Default matches any origin. */
  base?: string;
  /** Replace the generated body/status for specific `operationId`s. */
  overrides?: Record<string, { status?: number; body?: unknown }>;
  /** Only generate handlers for these operation ids. */
  only?: readonly string[];
}

/**
 * MSW handlers for every OpenAPI operation, generated by `scripts/gen-msw.mjs`. Bodies are schema-shaped
 * placeholders; use `overrides` or `server.use(...)` for the data a test cares about.
 */
export function createHandlers(opts: CreateHandlersOptions = {}): HttpHandler[] {
  const base = opts.base ?? '*/api/v1';
  return mockOperations
    .filter((o: MockOperation) => !opts.only || opts.only.includes(o.id))
    .map((o) => {
      const ov = opts.overrides?.[o.id];
      const status = ov?.status ?? o.status;
      const body = ov && 'body' in ov ? ov.body : o.body;
      return http[o.method](`${base}${o.path}`, () =>
        status === 204 || body === null
          ? new HttpResponse(null, { status })
          : HttpResponse.json(body, { status }),
      );
    });
}
