#!/usr/bin/env node
// XC-TEST-003: generate MSW request handlers from openapi.json.
//
//   node scripts/gen-msw.mjs           write src/mocks/handlers.generated.ts
//   node scripts/gen-msw.mjs --check   exit 1 if the committed file differs (CI drift check)
//
// One handler per operation. The response is the lowest 2xx status with a synthesized example body built
// from the response schema (required properties only, first `oneOf` branch, one array element, depth
// capped). Output is deterministic so `--check` is a plain string comparison. Nothing is hand-edited:
// override per test with `server.use(...)`, or compose via `createHandlers({ overrides })`.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = resolve(root, 'openapi.json');
const outPath = resolve(root, 'src/mocks/handlers.generated.ts');
const MAX_DEPTH = 4;

const spec = JSON.parse(readFileSync(specPath, 'utf8'));

function resolveRef(ref) {
  const name = ref.replace('#/components/schemas/', '');
  const s = spec.components?.schemas?.[name];
  if (!s) throw new Error(`unresolved $ref ${ref}`);
  return s;
}

function typeOf(schema) {
  const t = schema.type;
  if (Array.isArray(t)) return t.find((x) => x !== 'null') ?? 'null';
  return t;
}

function stringExample(name, schema) {
  if (schema.enum?.length) return schema.enum.find((v) => v !== null) ?? null;
  if (schema.format === 'date-time' || /(_at|timestamp)$/i.test(name))
    return '2026-01-01T00:00:00.000Z';
  if (schema.format === 'uuid') return '00000000-0000-4000-8000-000000000000';
  if (/(^|_)id$/i.test(name) || name === 'id') return '1';
  return 'string';
}

/** Synthesize an example value. `seen` guards against $ref cycles. */
function example(schema, name = '', depth = 0, seen = new Set()) {
  if (!schema || typeof schema !== 'object') return null;
  if (schema.$ref) {
    if (seen.has(schema.$ref) && depth >= MAX_DEPTH) return null;
    const next = new Set(seen).add(schema.$ref);
    return example(resolveRef(schema.$ref), name, depth + 1, next);
  }
  if (schema.example !== undefined) return schema.example;
  if (schema.enum?.length) return schema.enum.find((v) => v !== null) ?? null;
  if (schema.allOf) {
    const parts = schema.allOf.map((s) => example(s, name, depth, seen));
    return parts.every((p) => p && typeof p === 'object' && !Array.isArray(p))
      ? Object.assign({}, ...parts)
      : (parts[0] ?? null);
  }
  const branches = schema.oneOf ?? schema.anyOf;
  if (branches) {
    const pick = branches.find((b) => b.type !== 'null') ?? branches[0];
    return example(pick, name, depth, seen);
  }
  switch (typeOf(schema)) {
    case 'string':
      return stringExample(name, schema);
    case 'integer':
      return typeof schema.minimum === 'number' ? schema.minimum : 0;
    case 'number':
      return 0;
    case 'boolean':
      return false;
    case 'array':
      if (depth >= MAX_DEPTH) return [];
      if (schema.prefixItems) {
        return schema.prefixItems.map((s) => example(s, name, depth + 1, seen));
      }
      return schema.items ? [example(schema.items, name, depth + 1, seen)] : [];
    case 'object':
    case undefined: {
      const props = schema.properties;
      if (!props) return {};
      if (depth >= MAX_DEPTH) return {};
      const required = new Set(schema.required ?? []);
      const out = {};
      for (const key of Object.keys(props).sort()) {
        if (required.has(key)) out[key] = example(props[key], key, depth + 1, seen);
      }
      return out;
    }
    default:
      return null;
  }
}

const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'options', 'head'];
const ops = [];
for (const [path, item] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b))) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    const codes = Object.keys(op.responses ?? {})
      .filter((c) => /^2\d\d$/.test(c))
      .sort();
    const status = Number(codes[0] ?? 200);
    const res = codes[0] ? op.responses[codes[0]] : undefined;
    const schema = res?.content?.['application/json']?.schema;
    const body = status === 204 || !schema ? null : example(schema);
    ops.push({
      id: op.operationId ?? `${method}_${path}`,
      method,
      path: path.replace(/\{([^}]+)\}/g, ':$1'),
      status,
      body,
    });
  }
}

const lines = [
  '// GENERATED by scripts/gen-msw.mjs from openapi.json (XC-TEST-003). Do not edit by hand.',
  '// Regenerate with `pnpm --filter @sideroom/api-client mocks:generate`; CI runs `mocks:check`.',
  '',
  'export interface MockOperation {',
  '  id: string;',
  "  method: 'get' | 'put' | 'post' | 'delete' | 'patch' | 'options' | 'head';",
  '  /** Path relative to the API base, with `:param` placeholders. */',
  '  path: string;',
  '  status: number;',
  '  body: unknown;',
  '}',
  '',
  'export const mockOperations: readonly MockOperation[] = [',
  ...ops.map((o) => `  ${JSON.stringify(o)},`),
  '];',
  '',
];
const out = lines.join('\n');

if (process.argv.includes('--check')) {
  const have = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (have !== out) {
    console.error(
      'MSW handlers are out of date with openapi.json. Run: pnpm --filter @sideroom/api-client mocks:generate',
    );
    process.exit(1);
  }
  console.log(`MSW handlers up to date (${ops.length} operations).`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, out);
  console.log(`wrote ${outPath} (${ops.length} operations)`);
}
